// streebogCache is the precomputed L transformation table:
// [byteN][byteVal] -> 64-bit contribution.
var streebogCache [8][256]uint64

func init() {
	for byteN := 0; byteN < 8; byteN++ {
		for byteValN := 0; byteValN < 256; byteValN++ {
			val := byteValN
			var res64 uint64
			for bitN := 0; bitN < 8; bitN++ {
				if val&0x80 != 0 {
					res64 ^= streebogA[(7-byteN)*8+bitN]
				}
				val <<= 1
			}
			streebogCache[byteN][byteValN] = res64
		}
	}
}

func newStreebog(size int) *streebog {
	if size != 32 && size != 64 {
		panic("streebog: size must be 32 or 64")
	}
	s := &streebog{size: size}
	s.reset()
	return s
}

// New256 returns a hash.Hash computing Streebog-256.
func New256() hash.Hash { return newStreebog(32) }

// New512 returns a hash.Hash computing Streebog-512.
func New512() hash.Hash { return newStreebog(64) }

func (s *streebog) reset() {
	s.buf = s.buf[:0]
	s.n = 0
	s.h = make([]byte, streebogBlockSize)
	s.chk = make([]byte, streebogBlockSize)
	if s.size == 32 {
		for i := range s.h {
			s.h[i] = 0x01
		}
	}
}

func (s *streebog) Size() int      { return s.size }
func (s *streebog) BlockSize() int { return streebogBlockSize }

func (s *streebog) Reset() { s.reset() }

func (s *streebog) Write(p []byte) (int, error) {
	s.buf = append(s.buf, p...)
	for len(s.buf) >= streebogBlockSize {
		block := s.buf[:streebogBlockSize]
		s.h = s.g(s.n, s.h, block)
		s.chk = s.add512(s.chk, block)
		s.n += streebogBlockSize * 8
		s.buf = s.buf[streebogBlockSize:]
	}
	return len(p), nil
}

func (s *streebog) Sum(in []byte) []byte {
	// Clone state so Sum does not destroy the running hash.
	h := make([]byte, len(s.h))
	copy(h, s.h)
	chk := make([]byte, len(s.chk))
	copy(chk, s.chk)

	// Padding: 0x01 at the first free byte, zeros elsewhere.
	buf := make([]byte, streebogBlockSize)
	copy(buf, s.buf)
	buf[len(s.buf)] = 0x01

	h = s.g(s.n, h, buf)

	// Length in bits, little-endian in the first 8 bytes.
	lenBits := s.n + uint64(len(s.buf))*8
	lenBlock := make([]byte, streebogBlockSize)
	binary.LittleEndian.PutUint64(lenBlock, lenBits)

	h = s.g(0, h, lenBlock)
	h = s.g(0, h, s.add512(chk, buf))

	out := in
	if s.size == 32 {
		out = append(out, h[32:]...)
	} else {
		out = append(out, h...)
	}
	return out
}

func (s *streebog) g(n uint64, h, data []byte) []byte {
	// K = h XOR n, with n in the first 8 bytes, little-endian.
	k := make([]byte, streebogBlockSize)
	copy(k, h)
	for i := 0; i < 8; i++ {
		k[i] ^= byte(n >> (8 * i))
	}

	// out = E(L(PS(k)), data) XOR h XOR data.
	out := s.e(s.l(s.ps(k)), data)
	for i := 0; i < streebogBlockSize; i++ {
		out[i] ^= h[i] ^ data[i]
	}
	return out
}

func (s *streebog) e(k, msg []byte) []byte {
	k = append([]byte{}, k...)
	msg = append([]byte{}, msg...)
	for i := 0; i < 12; i++ {
		msg = s.l(s.ps(streebogXor(k, msg)))
		k = s.l(s.ps(streebogXor(k, streebogC[i][:])))
	}
	return streebogXor(k, msg)
}

func (s *streebog) ps(data []byte) []byte {
	out := make([]byte, streebogBlockSize)
	for i := 0; i < streebogBlockSize; i++ {
		out[streebogTau[i]] = streebogPi[data[i]]
	}
	return out
}

func (s *streebog) l(data []byte) []byte {
	out := make([]byte, streebogBlockSize)
	for i := 0; i < 8; i++ {
		var res uint64
		for j := 0; j < 8; j++ {
			res ^= streebogCache[j][data[i*8+j]]
		}
		binary.LittleEndian.PutUint64(out[i*8:], res)
	}
	return out
}

func (s *streebog) add512(a, b []byte) []byte {
	res := make([]byte, streebogBlockSize)
	var carry uint16
	for i := 0; i < streebogBlockSize; i++ {
		sum := uint16(a[i]) + uint16(b[i]) + carry
		res[i] = byte(sum)
		carry = sum >> 8
	}
	return res
}

func streebogXor(a, b []byte) []byte {
	out := make([]byte, len(a))
	for i := range a {
		out[i] = a[i] ^ b[i]
	}
	return out
}
